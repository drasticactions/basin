namespace Basin.Shell.Nested;

/// <summary>
/// A direction on the workspace grid.
/// </summary>
public enum WorkspaceDirection
{
    /// <summary>
    /// One column to the left.
    /// </summary>
    Left,
    /// <summary>
    /// One column to the right.
    /// </summary>
    Right,
    /// <summary>
    /// One row up.
    /// </summary>
    Up,
    /// <summary>
    /// One row down.
    /// </summary>
    Down,
}

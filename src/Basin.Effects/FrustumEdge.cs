namespace Basin.Effects;

/// <summary>
/// Names the edge of a rectangle that a perspective rotation hinges about.
/// </summary>
public enum FrustumEdge
{
    /// <summary>
    /// The top edge.
    /// </summary>
    Top = 0,

    /// <summary>
    /// The right edge.
    /// </summary>
    Right = 1,

    /// <summary>
    /// The bottom edge.
    /// </summary>
    Bottom = 2,

    /// <summary>
    /// The left edge.
    /// </summary>
    Left = 3,
}

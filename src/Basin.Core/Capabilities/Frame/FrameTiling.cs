namespace Basin.Capabilities;

/// <summary>
/// The screen edge that a window is tiled against.
/// </summary>
public enum FrameTiling
{
    /// <summary>
    /// The window is not tiled.
    /// </summary>
    None,
    /// <summary>
    /// The window is tiled against the left edge.
    /// </summary>
    Left,
    /// <summary>
    /// The window is tiled against the right edge.
    /// </summary>
    Right,
}

namespace Basin.Themes.MsStyles;

/// <summary>
/// Selects the vertical alignment of a glyph or a true-size image in its part. The values are the uxtheme <c>VALIGN</c> values.
/// </summary>
public enum VerticalAlign
{
    /// <summary>
    /// The item aligns to the top edge.
    /// </summary>
    Top = 0,
    /// <summary>
    /// The item is centered vertically.
    /// </summary>
    Center = 1,
    /// <summary>
    /// The item aligns to the bottom edge.
    /// </summary>
    Bottom = 2,
}

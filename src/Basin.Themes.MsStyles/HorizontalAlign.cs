namespace Basin.Themes.MsStyles;

/// <summary>
/// Selects the horizontal alignment of a glyph or a true-size image in its part. The values are the uxtheme <c>HALIGN</c> values.
/// </summary>
public enum HorizontalAlign
{
    /// <summary>
    /// The item aligns to the left edge.
    /// </summary>
    Left = 0,
    /// <summary>
    /// The item is centered horizontally.
    /// </summary>
    Center = 1,
    /// <summary>
    /// The item aligns to the right edge.
    /// </summary>
    Right = 2,
}

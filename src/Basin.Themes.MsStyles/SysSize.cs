namespace Basin.Themes.MsStyles;

/// <summary>
/// Identifies a system size that a theme sets in its system metrics. Each value is the matching <see cref="ThemeProperty"/> ID. Sizes are in pixels at 96 DPI.
/// </summary>
public enum SysSize
{
    /// <summary>
    /// The width of a sizing border.
    /// </summary>
    SizingBorderWidth = 1201,
    /// <summary>
    /// The width of a vertical scroll bar.
    /// </summary>
    ScrollbarWidth = 1202,
    /// <summary>
    /// The height of a horizontal scroll bar.
    /// </summary>
    ScrollbarHeight = 1203,
    /// <summary>
    /// The width of a caption button.
    /// </summary>
    CaptionBarWidth = 1204,
    /// <summary>
    /// The height of a caption bar.
    /// </summary>
    CaptionBarHeight = 1205,
    /// <summary>
    /// The width of a small caption button.
    /// </summary>
    SMCaptionBarWidth = 1206,
    /// <summary>
    /// The height of a small caption bar.
    /// </summary>
    SMCaptionBarHeight = 1207,
    /// <summary>
    /// The width of a menu bar button.
    /// </summary>
    MenuBarWidth = 1208,
    /// <summary>
    /// The height of a menu bar.
    /// </summary>
    MenuBarHeight = 1209,
    /// <summary>
    /// The width of the padding around a window border.
    /// </summary>
    PaddedBorderWidth = 1210,
}

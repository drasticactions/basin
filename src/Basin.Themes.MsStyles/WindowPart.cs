namespace Basin.Themes.MsStyles;

/// <summary>
/// Identifies a part of the <c>WINDOW</c> theme class. The values are the uxtheme <c>WP_</c> part IDs.
/// </summary>
public enum WindowPart
{
    /// <summary>
    /// The caption bar of a window.
    /// </summary>
    Caption = 1,
    /// <summary>
    /// The caption bar of a small window, for example a tool window.
    /// </summary>
    SmallCaption = 2,
    /// <summary>
    /// The caption of a minimized window.
    /// </summary>
    MinCaption = 3,
    /// <summary>
    /// The caption of a minimized small window.
    /// </summary>
    SmallMinCaption = 4,
    /// <summary>
    /// The caption bar of a maximized window.
    /// </summary>
    MaxCaption = 5,
    /// <summary>
    /// The caption bar of a maximized small window.
    /// </summary>
    SmallMaxCaption = 6,
    /// <summary>
    /// The left frame edge.
    /// </summary>
    FrameLeft = 7,
    /// <summary>
    /// The right frame edge.
    /// </summary>
    FrameRight = 8,
    /// <summary>
    /// The bottom frame edge.
    /// </summary>
    FrameBottom = 9,
    /// <summary>
    /// The left frame edge of a small window.
    /// </summary>
    SmallFrameLeft = 10,
    /// <summary>
    /// The right frame edge of a small window.
    /// </summary>
    SmallFrameRight = 11,
    /// <summary>
    /// The bottom frame edge of a small window.
    /// </summary>
    SmallFrameBottom = 12,
    /// <summary>
    /// The system menu button.
    /// </summary>
    SysButton = 13,
    /// <summary>
    /// The system menu button of an MDI child window.
    /// </summary>
    MdiSysButton = 14,
    /// <summary>
    /// The minimize button.
    /// </summary>
    MinButton = 15,
    /// <summary>
    /// The minimize button of an MDI child window.
    /// </summary>
    MdiMinButton = 16,
    /// <summary>
    /// The maximize button.
    /// </summary>
    MaxButton = 17,
    /// <summary>
    /// The close button.
    /// </summary>
    CloseButton = 18,
    /// <summary>
    /// The close button of a small window.
    /// </summary>
    SmallCloseButton = 19,
    /// <summary>
    /// The close button of an MDI child window.
    /// </summary>
    MdiCloseButton = 20,
    /// <summary>
    /// The restore button.
    /// </summary>
    RestoreButton = 21,
    /// <summary>
    /// The restore button of an MDI child window.
    /// </summary>
    MdiRestoreButton = 22,
    /// <summary>
    /// The help button.
    /// </summary>
    HelpButton = 23,
    /// <summary>
    /// The help button of an MDI child window.
    /// </summary>
    MdiHelpButton = 24,
    /// <summary>
    /// The horizontal scroll bar of a window.
    /// </summary>
    HorizontalScroll = 25,
    /// <summary>
    /// The thumb of the horizontal scroll bar.
    /// </summary>
    HorizontalThumb = 26,
    /// <summary>
    /// The vertical scroll bar of a window.
    /// </summary>
    VerticalScroll = 27,
    /// <summary>
    /// The thumb of the vertical scroll bar.
    /// </summary>
    VerticalThumb = 28,
    /// <summary>
    /// The background of a dialog.
    /// </summary>
    Dialog = 29,
    /// <summary>
    /// The sizing template of the caption.
    /// </summary>
    CaptionSizingTemplate = 30,
    /// <summary>
    /// The sizing template of a small caption.
    /// </summary>
    SmallCaptionSizingTemplate = 31,
    /// <summary>
    /// The sizing template of the left frame edge.
    /// </summary>
    FrameLeftSizingTemplate = 32,
    /// <summary>
    /// The sizing template of the left frame edge of a small window.
    /// </summary>
    SmallFrameLeftSizingTemplate = 33,
    /// <summary>
    /// The sizing template of the right frame edge.
    /// </summary>
    FrameRightSizingTemplate = 34,
    /// <summary>
    /// The sizing template of the right frame edge of a small window.
    /// </summary>
    SmallFrameRightSizingTemplate = 35,
    /// <summary>
    /// The sizing template of the bottom frame edge.
    /// </summary>
    FrameBottomSizingTemplate = 36,
    /// <summary>
    /// The sizing template of the bottom frame edge of a small window.
    /// </summary>
    SmallFrameBottomSizingTemplate = 37,
    /// <summary>
    /// The whole window frame.
    /// </summary>
    Frame = 38,
    /// <summary>
    /// The window border.
    /// </summary>
    Border = 39,
}

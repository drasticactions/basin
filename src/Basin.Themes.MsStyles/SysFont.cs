namespace Basin.Themes.MsStyles;

/// <summary>
/// Identifies a system font that a theme sets in its system metrics. Each value is the matching <see cref="ThemeProperty"/> ID.
/// </summary>
public enum SysFont
{
    /// <summary>
    /// The font of a window caption.
    /// </summary>
    CaptionFont = 801,
    /// <summary>
    /// The font of a small caption, for example a tool window caption.
    /// </summary>
    SmallCaptionFont = 802,
    /// <summary>
    /// The font of a menu.
    /// </summary>
    MenuFont = 803,
    /// <summary>
    /// The font of a status bar.
    /// </summary>
    StatusFont = 804,
    /// <summary>
    /// The font of a message box.
    /// </summary>
    MsgBoxFont = 805,
    /// <summary>
    /// The font of an icon title.
    /// </summary>
    IconTitleFont = 806,
    /// <summary>
    /// The font of a first-level heading.
    /// </summary>
    Heading1Font = 807,
    /// <summary>
    /// The font of a second-level heading.
    /// </summary>
    Heading2Font = 808,
    /// <summary>
    /// The font of body text.
    /// </summary>
    BodyFont = 809,
}

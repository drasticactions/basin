namespace Basin.Themes.MsStyles;

/// <summary>
/// Identifies a system color that a theme sets in its system metrics. Each value is the matching <see cref="ThemeProperty"/> ID.
/// </summary>
public enum SysColor
{
    /// <summary>
    /// The color of the scroll bar track.
    /// </summary>
    Scrollbar = 1601,
    /// <summary>
    /// The color of the desktop.
    /// </summary>
    Background = 1602,
    /// <summary>
    /// The caption color of the active window.
    /// </summary>
    ActiveCaption = 1603,
    /// <summary>
    /// The caption color of an inactive window.
    /// </summary>
    InactiveCaption = 1604,
    /// <summary>
    /// The background color of a menu.
    /// </summary>
    Menu = 1605,
    /// <summary>
    /// The background color of a window.
    /// </summary>
    Window = 1606,
    /// <summary>
    /// The color of a window frame.
    /// </summary>
    WindowFrame = 1607,
    /// <summary>
    /// The text color of a menu.
    /// </summary>
    MenuText = 1608,
    /// <summary>
    /// The text color of a window.
    /// </summary>
    WindowText = 1609,
    /// <summary>
    /// The caption text color of the active window.
    /// </summary>
    CaptionText = 1610,
    /// <summary>
    /// The border color of the active window.
    /// </summary>
    ActiveBorder = 1611,
    /// <summary>
    /// The border color of an inactive window.
    /// </summary>
    InactiveBorder = 1612,
    /// <summary>
    /// The background color of a multiple-document interface (MDI) workspace.
    /// </summary>
    AppWorkspace = 1613,
    /// <summary>
    /// The background color of selected items.
    /// </summary>
    Highlight = 1614,
    /// <summary>
    /// The text color of selected items.
    /// </summary>
    HighlightText = 1615,
    /// <summary>
    /// The face color of a three-dimensional control.
    /// </summary>
    BtnFace = 1616,
    /// <summary>
    /// The shadow color of a three-dimensional control.
    /// </summary>
    BtnShadow = 1617,
    /// <summary>
    /// The color of disabled text.
    /// </summary>
    GrayText = 1618,
    /// <summary>
    /// The text color of a push button.
    /// </summary>
    BtnText = 1619,
    /// <summary>
    /// The caption text color of an inactive window.
    /// </summary>
    InactiveCaptionText = 1620,
    /// <summary>
    /// The highlight color of a three-dimensional control.
    /// </summary>
    BtnHighlight = 1621,
    /// <summary>
    /// The dark shadow color of a three-dimensional control.
    /// </summary>
    DkShadow3D = 1622,
    /// <summary>
    /// The light color of a three-dimensional control.
    /// </summary>
    Light3D = 1623,
    /// <summary>
    /// The text color of a tooltip.
    /// </summary>
    InfoText = 1624,
    /// <summary>
    /// The background color of a tooltip.
    /// </summary>
    InfoBk = 1625,
    /// <summary>
    /// The alternate face color of a button.
    /// </summary>
    ButtonAlternateFace = 1626,
    /// <summary>
    /// The color of a hot-tracked item.
    /// </summary>
    HotTracking = 1627,
    /// <summary>
    /// The second gradient color of the active caption.
    /// </summary>
    GradientActiveCaption = 1628,
    /// <summary>
    /// The second gradient color of an inactive caption.
    /// </summary>
    GradientInactiveCaption = 1629,
    /// <summary>
    /// The highlight color of a flat menu item.
    /// </summary>
    MenuHilight = 1630,
    /// <summary>
    /// The background color of a flat menu bar.
    /// </summary>
    MenuBar = 1631,
}

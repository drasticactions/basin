namespace Basin.Themes.MsStyles;

/// <summary>
/// Selects the horizontal alignment of content, for example the caption text. The values are the uxtheme <c>CONTENTALIGNMENT</c> values.
/// </summary>
public enum ContentAlignment
{
    /// <summary>
    /// The content aligns to the left edge.
    /// </summary>
    Left = 0,
    /// <summary>
    /// The content is centered.
    /// </summary>
    Center = 1,
    /// <summary>
    /// The content aligns to the right edge.
    /// </summary>
    Right = 2,
}

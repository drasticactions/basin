namespace Basin.Themes.MsStyles;

/// <summary>
/// Selects how the frames of a multi-state image are arranged in the image. The values are the uxtheme <c>IMAGELAYOUT</c> values.
/// </summary>
public enum ImageLayout
{
    /// <summary>
    /// The frames stack from top to bottom.
    /// </summary>
    Vertical = 0,
    /// <summary>
    /// The frames are side by side from left to right.
    /// </summary>
    Horizontal = 1,
}
